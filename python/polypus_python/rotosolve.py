"""Whether a Qiskit circuit qualifies for ``polypus.Rotosolve`` (issue #398).

Rotosolve moves one parameter at a time to the maximum of the sinusoid the
fitness traces along it, from three values. That is exact when every trainable
parameter is the angle of exactly one rotation generated by a single Pauli
operator (or a phase gate), as ``±θ + c``: then, with the others fixed, every
outcome probability is ``a + A·cos θ + B·sin θ`` (M. Ostaszewski, E. Grant and
M. Benedetti, "Structure optimization for parameterized quantum circuits",
Quantum 5, 391 (2021), doi:10.22331/q-2021-01-28-391, arXiv:1905.09692; K. M.
Nakanishi, K. Fujii and S. Todo, "Sequential minimal optimization for
quantum-classical hybrid algorithms", Phys. Rev. Research 2, 043158 (2020),
doi:10.1103/PhysRevResearch.2.043158, arXiv:1903.12166). ``polypus.train``
and ``polypus.qml.train`` call :func:`single_frequency_problem` on a Qiskit
circuit before anything runs; a ``polypus.Circuit`` is checked in Rust, by
the same rules.

The circuit is read as it is bound: ``train`` hands the bound Qiskit circuit to
Aer or CUNQA, which lower only what their basis lacks, by exact synthesis. So
the check walks ``circuit.data`` and, for a composite gate (the single
instruction Qiskit's library classes such as ``RealAmplitudes`` build, or a
``to_gate()`` of a circuit), its definition, the exact decomposition the
lowering expands.
"""

from qiskit.circuit import ParameterExpression, QuantumCircuit
from qiskit.circuit.library import get_standard_gate_name_mapping

#: The standard gates whose one angle is a single-frequency rotation: generated
#: by a Pauli operator (``rx``, ``ry``, ``rz``, ``rxx``, ``ryy``, ``rzz``,
#: ``rzx``), or a phase (``p``, ``u1``, generated by ``|1⟩⟨1|``).
ROTATIONS = frozenset({"rx", "ry", "rz", "rxx", "ryy", "rzz", "rzx", "p", "u1"})

_STANDARD = get_standard_gate_name_mapping()


def single_frequency_problem(circuit, trainable=None):
    """The first reason ``circuit`` does not qualify for Rotosolve, or ``None``.

    ``trainable`` are the parameters Rotosolve trains (``None``: every
    parameter of the circuit, as ``polypus.train`` binds them all;
    ``qml.train`` passes the ansatz's). Any other parameter, such as a feature
    map's, is bound to a number before anything runs, so it is a constant and
    may appear anywhere.

    Each trainable parameter must be the angle of exactly one ``rx``, ``ry``,
    ``rz``, ``rxx``, ``ryy``, ``rzz``, ``rzx``, ``p`` or ``u1``, as ``±θ + c``,
    with ``c`` free of other trainable parameters. The instructions are walked
    in order, and the first gate that breaks this is reported; then each
    trainable parameter, in order, that appears more than once or nowhere.
    The circuit's ``global_phase`` changes no count, so it is not read.
    """
    if not isinstance(circuit, QuantumCircuit):
        raise TypeError(
            "polypus.Rotosolve trains a polypus.Circuit or a Qiskit QuantumCircuit, "
            f"got {type(circuit).__name__}"
        )
    order = list(circuit.parameters if trainable is None else trainable)
    occurrences = {parameter: [] for parameter in order}
    problem = _walk(circuit, frozenset(order), occurrences, "")
    if problem is not None:
        return problem
    for parameter in order:
        found = occurrences[parameter]
        if len(found) > 1:
            return (
                f"parameter '{parameter.name}' is in {len(found)} angles, first of "
                f"{found[0]} and then of {found[1]}"
            )
        if not found:
            return f"parameter '{parameter.name}' is in no gate"
    return None


def _walk(circuit, trainable, occurrences, prefix):
    """Record each trainable angle of ``circuit`` in ``occurrences``; return the
    first problem found, or ``None``. ``prefix`` locates ``circuit`` inside the
    composite gates around it."""
    for index, instruction in enumerate(circuit.data):
        operation = instruction.operation
        where = f"{prefix}instruction {index}"
        used = _trainable_in(operation, trainable)
        if not used:
            continue
        name = operation.name
        named = f"'{name}' ({where})"
        first = used[0].name
        if hasattr(operation, "blocks"):
            return (
                f"parameter '{first}' is used inside the control-flow block of {named}"
            )
        if _is_standard(operation):
            if name not in ROTATIONS:
                return (
                    f"parameter '{first}' is an angle of {named}, which is not a "
                    "rotation generated by a single Pauli operator"
                )
            problem, parameter = _angle_problem(operation.params[0], used, named)
            if problem is not None:
                return problem
            if parameter is not None:
                occurrences[parameter].append(named)
            continue
        try:
            definition = operation.definition
        except Exception:  # noqa: BLE001 - one Qiskit cannot build is none to check
            # e.g. HamiltonianGate, whose definition needs its time bound.
            definition = None
        if definition is None:
            return (
                f"parameter '{first}' is an angle of {named}, which has no definition "
                "to check"
            )
        inner = set(definition.parameters)
        hidden = [parameter for parameter in used if parameter not in inner]
        if hidden:
            return (
                f"parameter '{hidden[0].name}' is an argument of {named}, whose "
                "definition does not use it directly"
            )
        problem = _walk(
            definition,
            trainable,
            occurrences,
            f"{prefix}instruction {index} ('{name}') > ",
        )
        if problem is not None:
            return problem
    return None


def _trainable_in(operation, trainable):
    """The trainable parameters ``operation`` refers to, in a stable order: in
    its angles, or in its blocks for a control-flow operation."""
    found = set()
    for value in operation.params:
        if isinstance(value, (ParameterExpression, QuantumCircuit)):
            found.update(value.parameters)
    return sorted(found & trainable, key=lambda parameter: parameter.name)


def _is_standard(operation):
    """Whether ``operation`` is the standard gate its name says, not a custom
    gate that took the name."""
    standard = _STANDARD.get(operation.name)
    return standard is not None and getattr(operation, "base_class", None) is getattr(
        standard, "base_class", type(standard)
    )


def _angle_problem(angle, used, named):
    """Why ``angle``, which refers to the trainable ``used``, is not ``±θ + c``
    for one of them with ``c`` free of the others, or ``None``; and that
    parameter, which is ``None`` when the angle does not depend on any."""
    real = [parameter for parameter in used if _depends_on(angle, parameter)]
    if not real:
        return None, None
    parameter = real[0]
    lead = f"the angle of {named} is not ±{parameter.name} + c"
    if len(real) > 1:
        return f"{lead}: it also depends on parameter '{real[1].name}'", parameter
    try:
        slope = angle.gradient(parameter)
    except Exception:  # noqa: BLE001 - any failure means "cannot differentiate"
        return f"{lead}: Qiskit cannot differentiate it", parameter
    if _depends_on(slope, parameter):
        return f"{lead}: it is not linear in the parameter", parameter
    if isinstance(slope, ParameterExpression):
        symbols = sorted(slope.parameters, key=lambda symbol: symbol.name)
        for symbol in symbols:
            if _depends_on(slope, symbol):
                return (
                    f"{lead}: its coefficient depends on parameter '{symbol.name}', so "
                    "it is not ±1 for every value"
                ), parameter
        # Qiskit keeps the symbols of the expression it differentiated; the
        # slope depends on none of them, so any values give the constant.
        slope = _at(slope, _PROBES[0])
    slope = complex(slope)
    if slope.imag != 0 or slope.real not in (1.0, -1.0):
        shown = _shortest(slope.real) if slope.imag == 0 else f"{slope}"
        return f"{lead}: its coefficient is {shown}, not ±1", parameter
    return None, parameter


def _shortest(value):
    """``value`` in the fewest digits that read back as it, without a
    trailing ``.0``: ``2``, ``0.5``, ``0.9999999999999999``, as the Rust check
    prints its coefficients."""
    shown = repr(value)
    return shown[:-2] if shown.endswith(".0") else shown


def _depends_on(expression, parameter):
    """Whether ``expression`` depends on ``parameter``: its derivative is not
    zero. Qiskit keeps the symbols of an expression it differentiated in the
    derivative's ``parameters``, and does not always fold a zero (``1/x``
    differentiated by ``t`` is ``-0/x/x``), so neither says."""
    if not isinstance(expression, ParameterExpression):
        return False
    if parameter not in expression.parameters:
        return False
    try:
        derivative = expression.gradient(parameter)
    except Exception:  # noqa: BLE001 - when in doubt, it depends
        return True
    if not isinstance(derivative, ParameterExpression):
        return derivative != 0
    # A zero that is not folded is zero wherever it is evaluated; anything
    # else is not zero at all of these generic points.
    try:
        return any(complex(_at(derivative, probe)) != 0 for probe in _PROBES)
    except Exception:  # noqa: BLE001 - when in doubt, it depends
        return True


#: Generic values to evaluate an expression at, one per symbol in turn.
_PROBES = (
    (0.3719, 1.1347, -0.7183),
    (1.4142, -0.5772, 0.6931),
    (-1.2599, 0.9163, 2.7183),
)


def _at(expression, probe):
    """``expression`` with its symbols bound to the values of ``probe``, in
    turn, by name order."""
    symbols = sorted(expression.parameters, key=lambda symbol: symbol.name)
    return expression.bind(
        {
            symbol: probe[k % len(probe)] + k // len(probe)
            for k, symbol in enumerate(symbols)
        }
    )
