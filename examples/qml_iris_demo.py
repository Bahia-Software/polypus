SPECIES = ["setosa", "versicolor", "virginica"]


def load_iris():
    """Parse the embedded CSV into rows of features and class indices."""
    x, y = [], []
    for line in _IRIS_CSV.strip().splitlines():
        *features, label = line.split(",")
        x.append([float(v) for v in features])
        y.append(int(label))
    return x, y


def accuracy(predictions, labels):
    return sum(p == y for p, y in zip(predictions, labels)) / len(labels)


def main():
    print("Native QML on the Iris dataset\n")

    x, y = load_iris()
    train, test = qml.Dataset(x, y).train_test_split(0.2, seed=42)
    print(f"Iris: {len(x)} flowers, 4 features, 3 species")
    print(f"Split: {train.num_samples} train / {test.num_samples} test (seed=42)\n")

    # Scale both partitions with the train set's ranges only: the test set must
    # not influence anything the model sees.
    ranges = train.feature_ranges()
    train.scale_features_to(0.0, math.pi)
    test.scale_features_with(ranges, 0.0, math.pi)

    model = qml.Model(
        qml.Encoder(4).angle_encoder("ry"),
        qml.Ansatz(4).hardware_efficient(2),
        qml.Readout([qml.Z(0), qml.Z(1), qml.Z(2)], decision="argmax"),
    )
    print(f"Model: {model!r}\n")

    print("Training (Adam, exact gradient, no shot noise)...")
    started = time.perf_counter()
    result = model.fit(
        train,
        method=polypus.Adam(max_iters=100, learning_rate=0.1),
        loss="categorical_cross_entropy",
        exact=True,
        seed=42,
        id="iris_demo",
    )
    elapsed = time.perf_counter() - started
    print(
        f"Done in {elapsed:.1f}s: {result.iterations_run} iterations "
        f"(converged={result.converged})"
    )
    print(
        f"Fitness: {result.fitness_history[0]:+.4f} -> "
        f"{result.fitness_history[-1]:+.4f} (higher is better)\n"
    )

    trained = model.bind(result.best_params)
    train_predictions = trained.predict(train, exact=True)
    test_predictions = trained.predict(test, exact=True)
    print(
        f"Train accuracy: {accuracy(train_predictions, train.labels):.1%} "
        f"({train.num_samples} flowers)"
    )
    print(
        f"Test accuracy:  {accuracy(test_predictions, test.labels):.1%} "
        f"({test.num_samples} flowers never seen in training)\n"
    )

    print("Test predictions:")
    for predicted, actual in zip(test_predictions, test.labels):
        mark = "✅" if predicted == actual else "❌"
        print(
            f"  {mark} predicted {SPECIES[predicted]:<10} "
            f"(actual {SPECIES[int(actual)]})"
        )


if __name__ == "__main__":
    main()
