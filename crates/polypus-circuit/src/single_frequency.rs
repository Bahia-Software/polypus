    #[test]
    fn a_repeated_parameter_is_rejected_naming_both_gates() {
        let qc = ParameterizedCircuit::new(2)
            .ry(0, Param(0))
            .ry(1, Param(1))
            .rz(1, Param(0))
            .rx(0, Param(0));
        let err = qc.check_single_frequency().unwrap_err();
        assert_eq!(
            err,
            SingleFrequencyError::Repeated {
                param: 0,
                name: "theta_0".into(),
                count: 3,
                first: ("ry".into(), 0),
                second: ("rz".into(), 2),
            }
        );
        assert_eq!(
            err.to_string(),
            "parameter 0 ('theta_0') is in 3 angles, first of 'ry' (instruction 0) and then \
             of 'rz' (instruction 2)"
        );
    }

    #[test]
    fn a_coefficient_other_than_one_is_rejected() {
        let err = rz(2.0 * x(0)).check_single_frequency().unwrap_err();
        assert_eq!(
            err,
            SingleFrequencyError::Angle {
                param: 0,
                name: "theta_0".into(),
                gate: "rz".into(),
                instruction: 0,
                form: AngleForm::Coefficient(2.0),
            }
        );
        assert_eq!(
            err.to_string(),
            "the angle of 'rz' (instruction 0) is not ±Param(0) + c for parameter 0 \
             ('theta_0'): its coefficient is 2, not ±1"
        );
        for (expr, a) in [(0.5 * x(0), 0.5), (x(0) - x(0), 0.0), (x(0) + x(0), 2.0)] {
            assert!(matches!(
                rz(expr).check_single_frequency(),
                Err(SingleFrequencyError::Angle {
                    form: AngleForm::Coefficient(got),
                    ..
                }) if got == a
            ));
        }
        // ±1 exactly, however written.
        for expr in [-x(0), x(0) * 3.0 / 3.0, 1.0 - x(0), (x(0) + 0.1) / 1.0] {
            assert_eq!(rz(expr).check_single_frequency(), Ok(()));
        }
    }

    #[test]
    fn a_nonlinear_or_shared_angle_is_rejected() {
        let err = rz(x(0) * x(0)).check_single_frequency().unwrap_err();
        assert!(matches!(
            err,
            SingleFrequencyError::Angle {
                param: 0,
                form: AngleForm::NotAffine,
                ..
            }
        ));
        assert!(err
            .to_string()
            .ends_with("it is not linear in the parameter"));
        let err = rz(x(0).apply(Function::Sin)).check_single_frequency();
        assert!(matches!(
            err,
            Err(SingleFrequencyError::Angle {
                form: AngleForm::NotAffine,
                ..
            })
        ));
        let err = rz(x(0) + x(1)).check_single_frequency().unwrap_err();
        assert_eq!(
            err,
            SingleFrequencyError::Angle {
                param: 0,
                name: "theta_0".into(),
                gate: "rz".into(),
                instruction: 0,
                form: AngleForm::Shared { other: 1 },
            }
        );
        assert!(err.to_string().ends_with("it also depends on parameter 1"));
    }

    #[test]
    fn a_controlled_or_multi_angle_gate_is_rejected() {
        type Build = fn(ParameterizedCircuit) -> ParameterizedCircuit;
        let cases: [(&str, Build); 8] = [
            ("crx", |qc| qc.crx(0, 1, Param(0))),
            ("cry", |qc| qc.cry(0, 1, Param(0))),
            ("crz", |qc| qc.crz(0, 1, Param(0))),
            ("cp", |qc| qc.cp(0, 1, Param(0))),
            ("cu1", |qc| qc.cu1(0, 1, Param(0))),
            ("cu3", |qc| qc.cu3(0, 1, Param(0), 0.0, 0.0)),
            ("cu", |qc| qc.cu(0, 1, 0.0, Param(0), 0.0, 0.0)),
            ("u0", |qc| qc.u0(0, Param(0))),
        ];
        for (gate, build) in cases {
            let qc = build(ParameterizedCircuit::new(2).h(0));
            let err = qc.check_single_frequency().unwrap_err();
            assert_eq!(
                err,
                SingleFrequencyError::Generator {
                    param: 0,
                    name: "theta_0".into(),
                    gate: gate.into(),
                    instruction: 1,
                },
                "{gate}"
            );
            assert_eq!(
                err.to_string(),
                format!(
                    "parameter 0 ('theta_0') is an angle of '{gate}' (instruction 1), which is \
                     not a rotation generated by a single Pauli operator"
                )
            );
        }
        // The gate is reported before a repetition or the angle's form.
        let qc = ParameterizedCircuit::new(2)
            .ry(0, Param(0))
            .crx(0, 1, Param(0));
        assert!(matches!(
            qc.check_single_frequency(),
            Err(SingleFrequencyError::Generator { instruction: 1, .. })
        ));
    }

