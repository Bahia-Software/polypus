def test_a_repeated_parameter_names_its_first_two_gates():
    qc = QuantumCircuit(2)
    qc.ry(t, 0)
    qc.h(1)
    qc.rz(-t, 1)
    qc.rx(t + 1, 0)
    assert single_frequency_problem(qc) == (
        "parameter 't' is in 3 angles, first of 'ry' (instruction 0) and then of "
        "'rz' (instruction 2)"
    )


def test_a_parameter_in_no_gate_is_rejected():
    # Only the global phase uses it, which changes no count.
    qc = QuantumCircuit(1)
    qc.global_phase = t
    qc.ry(s, 0)
    assert single_frequency_problem(qc) == "parameter 't' is in no gate"
    # An ansatz parameter the composed circuit does not contain.
    assert single_frequency_problem(QuantumCircuit(1), [t]) == (
        "parameter 't' is in no gate"
    )


def test_a_gate_problem_comes_before_a_repeated_parameter():
    qc = QuantumCircuit(2)
    qc.ry(t, 0)
    qc.ry(t, 1)
    qc.crz(s, 0, 1)
    assert single_frequency_problem(qc).startswith("parameter 's' is an angle of 'crz'")


def test_anything_but_a_circuit_is_a_type_error():
    with pytest.raises(TypeError, match="got str"):
        single_frequency_problem("OPENQASM 2.0;")
