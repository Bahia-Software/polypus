@pytest.mark.parametrize(
    ("angle", "trainable", "reason"),
    [
        (2 * t, None, "its coefficient is 2, not ±1"),
        (0.5 * t + 1, None, "its coefficient is 0.5, not ±1"),
        (2 * (t + x), [t], "its coefficient is 2, not ±1"),
        (t * t, None, "it is not linear in the parameter"),
        (t.sin(), None, "it is not linear in the parameter"),
        ((t * x).exp(), [t], "it is not linear in the parameter"),
        (
            x * t,
            [t],
            "its coefficient depends on parameter 'x', so it is not ±1 for every value",
        ),
        (
            t / x,
            [t],
            "its coefficient depends on parameter 'x', so it is not ±1 for every value",
        ),
        (t + s, None, "it also depends on parameter 't'"),
    ],
    ids=["2t", "t/2 + 1", "2(t + x)", "t²", "sin t", "exp(tx)", "xt", "t/x", "s + t"],
)
def test_an_angle_that_is_not_plus_or_minus_the_parameter_is_rejected(
    angle, trainable, reason
):
    first = "s" if reason.endswith("parameter 't'") else "t"
    assert one_angle(angle, trainable) == (
        f"the angle of 'ry' (instruction 0) is not ±{first} + c: {reason}"
    )


def test_a_coefficient_is_shown_in_full():
    # Qiskit does not fold t + sin t − sin t, and evaluates its slope,
    # 1 + cos t − cos t, in floating point, where it can miss 1 by a rounding
    # error. The message then shows the coefficient it found, not a "1" that
    # reads as if 1 were rejected.
    problem = one_angle(t + t.sin() - t.sin())
    assert problem is None or "its coefficient is 1, not" not in problem
    assert _shortest(0.9999999999999999) == "0.9999999999999999"
    assert _shortest(1.0000000000000002) == "1.0000000000000002"
    assert (_shortest(2.0), _shortest(-0.5), _shortest(-3.0)) == ("2", "-0.5", "-3")


def test_an_angle_folded_back_to_the_parameter_qualifies():
    # x·t/x is t, whatever x.
    assert one_angle(t * x / x, [t]) is None


