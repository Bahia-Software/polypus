@pytest.mark.parametrize("gate", ["crx", "cry", "crz", "cp"])
def test_a_controlled_rotation_is_rejected(gate):
    qc = QuantumCircuit(2)
    getattr(qc, gate)(t, 0, 1)
    assert single_frequency_problem(qc) == (
        f"parameter 't' is an angle of '{gate}' (instruction 0), which is not a "
        "rotation generated by a single Pauli operator"
    )


@pytest.mark.parametrize(
    "build",
    [
        lambda qc: qc.append(CU1Gate(t), [0, 1]),
        lambda qc: qc.u(t, 0.1, 0.2, 0),
        lambda qc: qc.r(t, 0.3, 0),
    ],
    ids=["cu1", "u", "r"],
)
def test_other_standard_gates_are_rejected(build):
    qc = QuantumCircuit(2)
    build(qc)
    name = qc.data[0].operation.name
    assert single_frequency_problem(qc) == (
        f"parameter 't' is an angle of '{name}' (instruction 0), which is not a "
        "rotation generated by a single Pauli operator"
    )


def test_a_custom_gate_that_takes_a_rotations_name_is_not_one():
    qc = QuantumCircuit(1)
    qc.append(Gate("rx", 1, [t]), [0])
    assert single_frequency_problem(qc) == (
        "parameter 't' is an angle of 'rx' (instruction 0), which has no definition "
        "to check"
    )


class _Undefinable(Gate):
    """A custom gate whose definition fails to build."""

    def __init__(self, angle):
        super().__init__("undefinable", 1, [angle])

    def _define(self):
        raise RuntimeError("no definition for you")


@pytest.mark.parametrize(
    ("gate", "name"),
    [
        # Qiskit builds its definition from the matrix, which needs t bound.
        (HamiltonianGate([[1, 0], [0, -1]], t), "hamiltonian"),
        (_Undefinable(t), "undefinable"),
    ],
    ids=["HamiltonianGate", "raising _define"],
)
def test_a_gate_whose_definition_cannot_be_built_has_none_to_check(gate, name):
    qc = QuantumCircuit(1)
    qc.append(gate, [0])
    assert single_frequency_problem(qc) == (
        f"parameter 't' is an angle of '{name}' (instruction 0), which has no "
        "definition to check"
    )


def test_a_composite_gate_is_checked_through_its_definition():
    inner = QuantumCircuit(2, name="block")
    inner.ry(t, 0)
    inner.crx(s, 0, 1)
    qc = QuantumCircuit(2)
    qc.h(0)
    qc.append(inner.to_gate(), [0, 1])
    assert single_frequency_problem(qc) == (
        "parameter 's' is an angle of 'crx' (instruction 1 ('block') > instruction 1), "
        "which is not a rotation generated by a single Pauli operator"
    )


def test_an_evolution_by_a_pauli_doubles_the_angle():
    # exp(−i·t·Z) is rz(2t): two periods per 2π of t.
    qc = QuantumCircuit(1)
    qc.append(PauliEvolutionGate(SparsePauliOp("Z"), time=t), [0])
    problem = single_frequency_problem(qc)
    assert problem.startswith("the angle of 'rz' (instruction 0 ('PauliEvolution') > ")
    assert problem.endswith("is not ±t + c: its coefficient is 2, not ±1")


def test_a_parameter_inside_control_flow_is_rejected():
    qc = QuantumCircuit(1)
    with qc.for_loop(range(2)):
        qc.ry(t, 0)
    assert single_frequency_problem(qc) == (
        "parameter 't' is used inside the control-flow block of 'for_loop' "
        "(instruction 0)"
    )


