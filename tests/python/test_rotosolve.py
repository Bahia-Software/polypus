def test_every_single_pauli_rotation_and_phase_qualifies():
    a = ParameterVector("a", 9)
    qc = QuantumCircuit(2)
    qc.rx(a[0], 0)
    qc.ry(a[1], 0)
    qc.rz(a[2], 1)
    qc.rxx(a[3], 0, 1)
    qc.ryy(a[4], 0, 1)
    qc.rzz(a[5], 0, 1)
    qc.rzx(a[6], 0, 1)
    qc.p(a[7], 0)
    qc.append(U1Gate(a[8]), [1])
    qc.cx(0, 1)
    qc.measure_all()
    assert single_frequency_problem(qc) is None


@pytest.mark.parametrize(
    "build",
    [
        lambda: real_amplitudes(3, reps=2),
        lambda: efficient_su2(3, reps=1),
        # The class builds one composite instruction; its definition is walked.
        lambda: RealAmplitudes(3, reps=2),
    ],
    ids=["real_amplitudes", "efficient_su2", "RealAmplitudes class"],
)
def test_hardware_efficient_ansatze_qualify(build):
    with warnings.catch_warnings():
        # The library classes are deprecated in favour of the functions.
        warnings.simplefilter("ignore", DeprecationWarning)
        circuit = build()
    assert single_frequency_problem(circuit) is None


@pytest.mark.parametrize(
    "angle",
    [-t, t + 0.3, 1.0 - t, 0.5 * t + 0.5 * t, t * 1.0],
    ids=["-t", "t + c", "c - t", "folded", "t * 1.0"],
)
def test_an_angle_of_plus_or_minus_the_parameter_plus_a_constant_qualifies(angle):
    assert one_angle(angle) is None


def test_a_non_trainable_parameter_is_a_constant_anywhere():
    # A feature map's parameters are bound per sample before anything runs.
    assert one_angle(t + x, [t]) is None
    assert one_angle(-(t + x), [t]) is None
    qc = QuantumCircuit(2)
    qc.crx(x, 0, 1)
    qc.ry(x, 0)
    qc.ry(t, 1)
    assert single_frequency_problem(qc, [t]) is None


def test_a_composed_feature_map_and_ansatz_qualifies_for_the_ansatz():
    feature_map = zz_feature_map(2, reps=1)
    ansatz = real_amplitudes(2, reps=1)
    composed = feature_map.compose(ansatz)
    composed.measure_all()
    assert single_frequency_problem(composed, ansatz.parameters) is None
    # Every parameter, the feature map's p(2·x) included, is another matter.
    assert single_frequency_problem(composed) is not None


