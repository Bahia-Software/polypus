"""
``polypus.Rotosolve`` (issue #398) and the check that a circuit qualifies for
it: every trainable parameter the angle of exactly one single-Pauli rotation,
as ``±θ + c``.

The check of a Qiskit circuit is ``polypus_python.rotosolve``, tested here on
its own; ``polypus.train`` and ``polypus.qml.train`` call it (and the Rust
check of a ``polypus.Circuit``) before anything runs.
"""

import math
import warnings

import pytest

pytest.importorskip("qiskit")

from polypus_python.rotosolve import (  # noqa: E402
    _shortest,
    single_frequency_problem,
)
from qiskit import QuantumCircuit  # noqa: E402
from qiskit.circuit import Gate, Parameter, ParameterVector  # noqa: E402
from qiskit.circuit.library import (  # noqa: E402
    CU1Gate,
    HamiltonianGate,
    PauliEvolutionGate,
    RealAmplitudes,
    U1Gate,
    efficient_su2,
    real_amplitudes,
    zz_feature_map,
)
from qiskit.quantum_info import SparsePauliOp  # noqa: E402

t, s, x = Parameter("t"), Parameter("s"), Parameter("x")


def one_angle(angle, trainable=None):
    qc = QuantumCircuit(1)
    qc.ry(angle, 0)
    return single_frequency_problem(qc, trainable)


